## [Обновление от 05.09.2026] (Дополнение)
### Добавлено
- Инструменты редактирования таблиц (добавление/удаление строк и столбцов, объединение/разделение ячеек, удаление таблицы). Меню управления появляется автоматически при установке курсора внутрь таблицы.
