### Дополнительные возможности редактора
- **Таблицы:** При клике на любую ячейку вставленной таблицы появляется специальное меню с действиями (добавление/удаление строк и столбцов, объединение ячеек).
- **Вставка HTML:** Вы можете вставлять любой сырой HTML код (например, Яндекс Карты или виджеты), нажав на иконку кода в панели инструментов.
- **Отступы:** Вы можете управлять отступами абзацев, используя иконки увеличения/уменьшения отступа на панели.

