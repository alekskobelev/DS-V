### Работа с новым визуальным редактором
В CMS интегрирован новый визуальный редактор статей и страниц.
Вам доступны функции: форматирование текста (цвет, фон, индексы), таблицы, вставка ссылок и картинок.
Для сохранения результата нажмите "Сохранить изменения" после редактирования контента в визуальном режиме.

### Загрузка изображений для товаров
При создании или редактировании продуктов в поле "URL изображения" теперь доступна кнопка "Загрузить файл", позволяющая выбрать файл с компьютера. Файл будет автоматически сохранен на сервере, а ссылка вставлена в поле.

### CRM
Доступ к CRM теперь осуществляется не через панель CMS, а через выпадающее меню профиля (клик на аватар пользователя -> "CRM-система").
