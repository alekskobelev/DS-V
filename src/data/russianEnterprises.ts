/**
 * Searches Russian enterprises database by INN, Name, City or Industry
 */
export function searchRussianEnterprises(queryText: string): RussianEnterprise[] {
  if (!queryText || !queryText.trim()) {
    return RUSSIAN_ENTERPRISES_REGISTRY.slice(0, 10);
  }

  const q = queryText.toLowerCase().trim();
  const digitsOnly = queryText.replace(/\D/g, '');

  const matches = RUSSIAN_ENTERPRISES_REGISTRY.filter(item => {
    if (digitsOnly && item.inn.includes(digitsOnly)) return true;
    if (digitsOnly && item.ogrn.includes(digitsOnly)) return true;
    if (item.name.toLowerCase().includes(q)) return true;
    if (item.fullName.toLowerCase().includes(q)) return true;
    if (item.shortName.toLowerCase().includes(q)) return true;
    if (item.city.toLowerCase().includes(q)) return true;
    if (item.ceoName.toLowerCase().includes(q)) return true;
    if (item.industry.toLowerCase().includes(q)) return true;
    return false;
  });

  if (matches.length > 0) {
    return matches;
  }

  // NEVER invent or synthesize fake companies!
  // Organizations not in the local offline registry must be searched via the live DaData API.
  return [];
}
